import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium } from 'playwright';
import { yearSwitcherFixtureConfig } from '../fixtures/school-year-switcher/config';
import { createFixtureServer } from './support/fixture-server';
import { chooseOption, selectOptions } from './support/custom-select';
import { ensurePlaywrightChromium } from '../../scripts/playwright-browsers';

async function main() {
  ensurePlaywrightChromium();
  const root = resolve(import.meta.dirname, '../..');
  const output = process.env.INTEGRATION_ARTIFACT_DIR ?? resolve(root, '.focused-run/school-year-switcher');
  mkdirSync(output, { recursive: true });
  const server = await createFixtureServer(yearSwitcherFixtureConfig(root), 'school-year-switcher', 14308, '/year-switcher');
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(12000);
  await page.addInitScript(() => localStorage.setItem('edaya:sidebarOpen', 'true'));
  const errors: string[] = [];
  const resourceErrors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') console.error(message.text()); });
  page.on('response', response => { if (response.status() >= 400) { resourceErrors.push(new URL(response.url()).pathname); console.error('Failed fixture resource', response.status(), response.url()); } });
  const trigger = page.getByTestId('academic-year-trigger');
  const dialog = page.getByTestId('academic-year-dialog');
  const choice = page.getByTestId('academic-year-choice');
  const apply = page.getByTestId('academic-year-apply');
  const guard = page.getByTestId('confirm-modal');
  const scope = async () => JSON.parse(await page.getByTestId('scope').innerText()) as { year: string; period: string; school: string; generation: number; cache: boolean };
  const external = (method: string, value?: string | boolean) => page.evaluate(({method, value}) => (window as any).yearFixture[method](value), {method, value});
  async function open() { await trigger.click(); await dialog.waitFor(); }
  try {
    await page.goto(server.url);
    await trigger.waitFor();
    await page.evaluate(() => document.fonts.ready);
    assert.equal(await trigger.innerText(), '2026–2027');
    assert.equal(await page.locator('#app-sidebar').getByTestId('academic-year-label').innerText(), 'School year');
    assert.equal(await page.locator('#app-sidebar').getByTestId('school-selector').count(), 0);
    assert.equal(await page.getByTestId('header-school').innerText(), 'Oak School');
    assert.equal(await trigger.getAttribute('aria-haspopup'), 'dialog');
    const triggerStyle = await trigger.evaluate(element => ({ border: getComputedStyle(element).borderWidth, padding: getComputedStyle(element).padding, height: element.getBoundingClientRect().height }));
    assert.equal(triggerStyle.border, '0px');
    assert.equal(triggerStyle.padding, '0px');
    assert(triggerStyle.height >= 44);
    await trigger.focus();
    await page.keyboard.press('Enter');
    await dialog.waitFor();
    assert(await choice.evaluate(element => element === document.activeElement), 'Year selector receives initial focus');
    assert(await apply.isDisabled());
    const options = await selectOptions(choice).evaluateAll(nodes => nodes.map(node => ({ value: (node as HTMLOptionElement).value, label: node.textContent })));
    assert.deepEqual(options.map(option => option.value), ['', 'draft', 'published', 'archived']);
    assert(options.find(option => option.value === 'draft')!.label?.includes('Draft'));
    assert(options.find(option => option.value === 'archived')!.label?.includes('Archived'));
    await chooseOption(choice, 'draft');
    assert.equal((await scope()).year, 'published', 'Preview never changes the selected year');
    assert((await page.getByTestId('academic-year-dates').innerText()).includes('2027'));
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert.equal((await scope()).year, 'published');
    assert(await trigger.evaluate(element => element === document.activeElement));
    await open();
    await chooseOption(choice, 'draft');
    await page.mouse.click(1200, 850);
    await dialog.waitFor({ state: 'hidden' });
    assert.equal((await scope()).year, 'published', 'Outside dismissal does not apply the preview');
    await page.getByTestId('seed-cache').click();
    assert((await scope()).cache);
    const generation = (await scope()).generation;
    await open();
    await chooseOption(choice, 'draft');
    await apply.click();
    await dialog.waitFor({ state: 'hidden' });
    const changed = await scope();
    assert.equal(changed.year, 'draft');
    assert.equal(changed.period, '', 'Years without periods do not borrow another year’s term');
    assert(changed.generation > generation);
    assert.equal(changed.cache, false, 'Confirmed switching evicts the previous academic read cache');
    assert.equal(await page.evaluate(() => sessionStorage.getItem('edaya:yearId:school')), 'draft');
    await page.reload();
    await trigger.waitFor();
    assert.equal((await scope()).year, 'draft');
    await open();
    await chooseOption(choice, 'published');
    await apply.click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal((await scope()).period, 'term');

    await page.getByLabel('Fixture draft').fill('Unsaved work');
    await open();
    await chooseOption(choice, 'archived');
    await apply.click();
    await guard.waitFor();
    await guard.getByRole('button', { name: 'Keep editing', exact: true }).click();
    await guard.waitFor({ state: 'hidden' });
    assert.equal((await scope()).year, 'published');
    assert.equal(await page.getByLabel('Fixture draft').inputValue(), 'Unsaved work');
    assert.equal(await selectOptions(choice).evaluateAll(nodes => (nodes as HTMLOptionElement[]).find(node => node.selected)?.value), 'archived');
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(await page.getByLabel('Fixture draft').inputValue(), 'Unsaved work', 'Cancel discards only the switcher preview');
    await open();
    await chooseOption(choice, 'archived');
    await apply.click();
    await guard.getByRole('button', { name: 'Discard changes', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal((await scope()).year, 'archived');
    assert.equal(await page.getByLabel('Fixture draft').inputValue(), '');

    await open();
    await chooseOption(choice, 'draft');
    await external('school', 'other');
    await dialog.waitFor({ state: 'hidden' });
    assert.equal((await scope()).year, 'other-year');
    await external('school', 'school');
    assert.equal((await scope()).year, 'archived', 'Each school retains its own selected year');
    await page.getByLabel('Fixture draft').fill('Pending dirty work');
    await open();
    await chooseOption(choice, 'draft');
    await apply.click();
    await guard.waitFor();
    await external('remove', 'draft');
    await guard.getByRole('button', { name: 'Discard changes', exact: true }).click();
    await guard.waitFor({ state: 'hidden' });
    await dialog.getByRole('alert').waitFor();
    assert.equal((await scope()).year, 'archived', 'A removed target cannot be applied by a deferred guard');
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await external('school', 'school');
    await page.getByLabel('Fixture draft').fill('Keep pending account work');
    await open();
    await chooseOption(choice, 'published');
    await apply.click();
    await guard.waitFor();
    await external('account');
    await dialog.waitFor({ state: 'hidden' });
    await guard.waitFor({ state: 'hidden' });
    assert.equal((await scope()).year, 'archived', 'Identity change cancels the switcher’s deferred continuation');
    await page.reload();
    await trigger.waitFor();
    await external('loading', true);
    assert(await trigger.isDisabled());
    assert((await trigger.innerText()).includes('Loading'));
    await external('loading', false);
    await external('missing');
    assert.equal(await trigger.innerText(), 'Select academic year', 'No first-year fallback may impersonate a missing selection');
    await external('empty');
    assert(await trigger.isDisabled());
    assert.equal(await trigger.innerText(), 'No school year available');
    await external('school', 'school');

    await external('multipleSchools');
    await page.getByTestId('school-selector-menu').click();
    await page.getByRole('option', { name: 'Other school', exact: true }).click();
    assert.equal((await scope()).school, 'other', 'Relocated school selector retains the existing switch workflow');
    assert((await page.getByTestId('header-school').innerText()).includes('Other school'));
    await page.getByTestId('school-selector-menu').click();
    await page.getByRole('option', { name: 'Oak School', exact: true }).click();
    assert.equal((await scope()).school, 'school');

    // The same trigger DOM node survives text/calendar changes, including hover pinning.
    await page.getByTestId('toggle-sidebar').click();
    await page.mouse.move(1000, 100);
    await page.locator('#app-sidebar').evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished)));
    assert.equal(await trigger.innerText(), '');
    await trigger.focus();
    await page.keyboard.press('Enter');
    await dialog.waitFor();
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert(await trigger.evaluate(element => element === document.activeElement));
    await page.mouse.move(20, 100);
    await page.waitForFunction(() => document.querySelector('#app-sidebar')!.getBoundingClientRect().width > 200);
    await open();
    await page.mouse.move(1000, 400);
    assert((await page.locator('#app-sidebar').boundingBox())!.width > 200, 'Opening from hover pins expanded navigation');
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert(await trigger.evaluate(element => element === document.activeElement));

    for (const language of ['en', 'fr']) for (const width of [360, 768, 1280]) for (const scale of [1, 2]) {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(`${server.url}?lang=${language}`);
      await trigger.waitFor({ state: width < 1024 ? 'hidden' : 'visible' });
      await page.evaluate(scale => { document.documentElement.style.fontSize = `${16 * scale}px`; }, scale);
      await external('longHeaderNames');
      await page.evaluate(() => document.fonts.ready);
      const header = page.getByTestId('app-header');
      const alignment = await header.evaluate(element => {
        const language = element.querySelector('[data-testid=language-selector]')!.getBoundingClientRect().toJSON();
        const profile = element.querySelector('[data-testid=user-menu]')!.getBoundingClientRect().toJSON();
        const actions = element.querySelector('[data-testid=header-actions]')!.getBoundingClientRect().toJSON();
        const school = element.querySelector('[data-testid=header-school]')!.getBoundingClientRect().toJSON();
        const nav = element.querySelector('[data-testid=navigation-toggle]')!.getBoundingClientRect().toJSON();
        const box = element.getBoundingClientRect().toJSON();
        return { language, profile, actions, school, nav, box, padding: Number.parseFloat(getComputedStyle(element).paddingRight), scroll: element.scrollWidth, client: element.clientWidth };
      });
      assert(Math.abs(alignment.language.y + alignment.language.height / 2 - alignment.profile.y - alignment.profile.height / 2) < 1, 'Language and profile stay on the same row');
      assert(Math.abs(alignment.language.right + 8 - alignment.profile.left) < 1, 'Language is grouped beside profile rather than centered');
      assert(Math.abs(alignment.profile.right - alignment.box.right + alignment.padding) < 1, 'Account/language group is pinned to header right');
      assert.equal(alignment.scroll, alignment.client, `${language}/${width}/${scale}: header has no horizontal overflow`);
      assert(alignment.school.left < alignment.actions.left && alignment.school.right <= alignment.box.right, 'School name stays left and remains bounded');
      await page.screenshot({ path: resolve(output, `header-${language}-${width}-${scale}.png`) });
      await page.getByTestId('language-selector').click();
      const languageMenu = page.getByTestId('language-menu');
      await languageMenu.waitFor();
      const languageBounds = await languageMenu.boundingBox();
      assert(languageBounds && languageBounds.x >= 15 && languageBounds.x + languageBounds.width <= width - 15, 'Language options remain inside the compact viewport');
      await page.keyboard.press('Escape');
      await languageMenu.waitFor({ state: 'hidden' });
      assert(await page.getByTestId('language-selector').evaluate(element => element === document.activeElement), 'Language dismissal returns focus to its trigger');
      await page.getByTestId('language-selector').click();
      await page.getByTestId(`language-option-${language}`).click();
      if (width < 1024) await page.getByTestId('navigation-toggle').click();
      await trigger.waitFor();
      if (width === 1280 && scale === 1) await page.locator('#app-sidebar').screenshot({ path: resolve(output, `sidebar-${language}-1280.png`) });
      await external('longLabel');
      await open();
      const box = await dialog.boundingBox();
      assert(box && box.x >= 15 && box.x + box.width <= width - 15, 'Dialog keeps shared gutters');
      assert(box.y >= 15 && box.y + box.height <= 885, 'Dialog fits short content area');
      assert(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), `${language}/${width}/${scale}: dialog content reflows`);
      await choice.click();
      const listbox = page.getByRole('listbox');
      await listbox.waitFor();
      const optionBox = await listbox.boundingBox();
      assert(optionBox && optionBox.x >= -1 && optionBox.x + optionBox.width <= width + 1, 'Year options stay in the viewport');
      await page.keyboard.press('Escape');
      await listbox.waitFor({ state: 'hidden' });
      await page.evaluate(() => document.fonts.ready);
      await page.screenshot({ path: resolve(output, `${language}-${width}-${scale}.png`) });
      if (language === 'fr' && width === 360 && scale === 2) {
        await page.setViewportSize({ width, height: 560 });
        await chooseOption(choice, 'draft');
        await page.getByRole('listbox').waitFor({ state: 'hidden' });
        const applyBox = await apply.boundingBox();
        assert(applyBox && applyBox.y >= 0 && applyBox.y + applyBox.height <= 560, 'Switch action remains reachable on short screens');
        await page.screenshot({ path: resolve(output, 'fr-360-2-short.png') });
      }
      await page.keyboard.press('Escape');
      await dialog.waitFor({ state: 'hidden' });
      assert(await trigger.evaluate(element => element === document.activeElement));
      if (width < 1024) {
        assert(await page.getByTestId('mobile-navigation').isVisible(), 'Closing the year dialog preserves the mobile navigation sheet');
        await page.keyboard.press('Escape');
        await page.getByTestId('mobile-navigation').waitFor({ state: 'hidden' });
      }
    }
    assert.deepEqual(errors, []);
    assert.deepEqual(resourceErrors, [], 'Review captures must use the bundled fonts and official artwork');
    writeFileSync(resolve(output, 'capture-conditions.json'), JSON.stringify({ tokenVersion: JSON.parse(readFileSync(resolve(root, '../../design-system/tokens.json'), 'utf8')).version, locales: ['en', 'fr'], viewportWidths: [360, 768, 1280], viewportHeights: [900, 560], textScales: [1, 2], source: 'execution.json', data: 'isolated fixture with production header/sidebar, academic context and dirty-work owner' }, null, 2));
    console.log('PASS: school-year dialog preview/confirm/cancel, all year states, dirty guards, identity/catalog safety, scoped persistence/cache/periods, collapsed/hover/mobile focus, right-pinned header controls and EN/FR 200% text');
  } catch (error) {
    await page.screenshot({ path: resolve(output, 'failure.png') });
    console.error('Page errors:', errors);
    console.error((await page.locator('body').innerText()).slice(-5000));
    throw error;
  } finally { await browser.close(); await server.close(); }
}
void main().catch(error => { console.error(error); process.exitCode = 1; });
