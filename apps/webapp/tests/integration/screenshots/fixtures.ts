import assert from 'node:assert/strict';
import type { Page } from 'playwright';
import { SEED_SCHOOL_ID } from '@edaya/web-fixtures';
import { emptyEntities, type MatrixEntities } from '../../../scripts/qa-matrix-support';
import { apiFetch } from '../setup/journey-api';
import { signInAccount } from '../support/api-provision';
import { CLASS_6A, CLASS_6B, STUDENT_ID, TEACHER_ID, STAFF_ID, GUARDIAN_ID, ACTIVITY_ID,
  CATALOG_SUBJECT_ID, CLASS_SUBJECT_ID, EVALUATION_ID, SEEDED_TIMETABLE_WEEK } from '../demo-dry-run/support/constants';

export function assertLocalEndpoint(value: string): void {
  const url = new URL(value);
  assert(url.protocol === 'http:' && ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname),
    'Screenshot fixtures require an http localhost endpoint');
}

/** Resolve records through admitted reads; never reset or wipe the caller's database. */
export async function resolveScreenshotFixtures(page: Page, base: string, apiUrl: string): Promise<MatrixEntities> {
  assertLocalEndpoint(base);
  assertLocalEndpoint(apiUrl);
  const list = async (entity: string, data: Record<string, unknown> = {}) => {
    const response = await apiFetch(page, base, `/core/entities/${entity}/list`, {
      method: 'POST', data: { schoolId: SEED_SCHOOL_ID, ...data }, schoolId: SEED_SCHOOL_ID,
    }, apiUrl);
    if (!response.ok()) throw new Error(`Fixture read ${entity}: HTTP ${response.status()}`);
    const body: unknown = await response.json();
    return (Array.isArray(body) ? body : (body as { items?: unknown[] })?.items ?? []) as Record<string, unknown>[];
  };
  const [classes, students] = await Promise.all([list('class-groups'), list('students')]);
  assert(classes.some(record => record.id === CLASS_6A) && students.some(record => record.id === STUDENT_ID),
    'Required demo-ci school/class/student missing. Start the test API and run bun repo seed against it.');
  const entities: MatrixEntities = { ...emptyEntities(), classId: CLASS_6A, secondClassId: CLASS_6B, studentId: STUDENT_ID,
    classStudentId: STUDENT_ID, staffId: STAFF_ID, teacherId: TEACHER_ID, guardianId: GUARDIAN_ID,
    activityId: ACTIVITY_ID, configurationSubjectId: CATALOG_SUBJECT_ID, subjectId: CATALOG_SUBJECT_ID,
    teachingId: CLASS_SUBJECT_ID, evaluationId: EVALUATION_ID, configClassId: CLASS_6A,
    timetableWeek: SEEDED_TIMETABLE_WEEK, eventId: 'ci-i1', gradeScaleId: 'ci-gs-20', reportCardDefId: 'ci-rcd-6',
    announcementId: 'ci-ann-draft-fete', notificationTemplateKey: 'report_card.published',
  } satisfies MatrixEntities;
  // Some data is generated by domain workflows, so resolve actual ids rather than guess them.
  const mappings: Array<[string, keyof MatrixEntities]> = [
    ['calendar-events', 'calendarEventId'], ['lesson-sessions', 'sessionId'], ['attendances', 'dayId'],
    ['results', 'reportCardId'], ['student-charges', 'billingId'], ['grade-levels', 'gradeLevelId'],
    ['message-deliveries', 'deliveryId'],
  ];
  for (const [entity, key] of mappings) {
    try {
      const rows = await list(entity, ['lesson-sessions', 'attendances'].includes(entity) ? { classGroupId: CLASS_6A } : {});
      const selected = rows.find(row => row.classGroupId === CLASS_6A && (row.studentId === STUDENT_ID || row.studentId == null))
        ?? rows.find(row => row.studentId === STUDENT_ID) ?? rows[0];
      if (typeof selected?.id === 'string') (entities as unknown as Record<string, unknown>)[key] = selected.id;
    } catch {
      // Optional domain absence fails its captures with an explicit missing-fixture diagnostic.
      // Required demo preflight above remains fatal.
    }
  }
  for (const [query, key] of [['list-family-feedback-campaigns', 'familyFeedbackCampaignId'], ['list-conversations', 'conversationId']] as const) {
    const response = await apiFetch(page, base, `/core/queries/${query}`, { method: 'POST', data: {}, schoolId: SEED_SCHOOL_ID }, apiUrl);
    if (response.ok()) {
      const body = await response.json() as Record<string, unknown>[] | { items?: Record<string, unknown>[] };
      const rows = Array.isArray(body) ? body : body.items ?? [];
      if (typeof rows[0]?.id === 'string') entities[key] = rows[0].id;
    }
  }
  if (!entities.conversationId) {
    // Seeded guardians already have an account link. Add a fictional question rather
    // than replace that link or modify an existing conversation.
    const guardian = await signInAccount(apiUrl, base, 'm.kone@mail.ci', '');
    const created = await guardian.jsonRequest<{ id: string }>('/core/commands/start-conversation', {
      method: 'POST', headers: { 'content-type': 'application/json', 'x-school-id': SEED_SCHOOL_ID,
        'x-actor-kind': 'guardian', 'x-actor-id': GUARDIAN_ID },
      body: JSON.stringify({ requestId: crypto.randomUUID(), destination: 'school', studentId: STUDENT_ID,
        subject: 'Screenshot demo question', body: 'Could you confirm the fictional school visit schedule?' }),
    });
    assert(created.response.ok && created.body?.id, `Disposable conversation fixture: HTTP ${created.response.status}`);
    entities.conversationId = created.body.id;
  }
  return entities;
}

export async function resolveScreenshotAcademicScope(page: Page, base: string, apiUrl: string) {
  const read = async (entity: string) => {
    const response = await apiFetch(page, base, `/core/entities/${entity}/list`, {
      method: 'POST', data: { schoolId: SEED_SCHOOL_ID }, schoolId: SEED_SCHOOL_ID,
    }, apiUrl);
    assert(response.ok(), `Academic fixture ${entity}: HTTP ${response.status()}`);
    return await response.json() as Array<{ id: string; academicYearId?: string; status?: string; startDate: string }>;
  };
  const years = await read('academic-years');
  const year = years.find(value => value.status === 'published');
  assert(year, 'Demo academic year must be published');
  const periods = (await read('academic-periods')).filter(value => value.academicYearId === year.id).sort((a, b) => a.startDate.localeCompare(b.startDate));
  assert(periods[0], 'Demo academic year must have periods');
  return { yearId: year.id, periodId: periods[0].id };
}
