import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { relative, resolve } from 'node:path'
import { digest, files, root, run, writeJson } from './runtime'

interface Tokens {
  version: string
  colors: Record<string, Record<string, string>>
  space: Record<string, number>
  radius: Record<string, number>
  motion: Record<string, number>
}
const design = resolve(root, 'design-system')
export function tokenCss(tokens: Tokens): string {
  const lines = ['/* Generated by bun run repo generate brand. Edit the manifest. */', ':root {']
  for (const [name, hex] of Object.entries(tokens.colors.light!)) {
    const [r, g, b] = [1, 3, 5].map(index => Number.parseInt(hex.slice(index, index + 2), 16) / 255) as [
      number,
      number,
      number,
    ]
    const max = Math.max(r, g, b)
    const min = Math.min(r, g, b)
    const delta = max - min
    const light = (max + min) / 2
    const saturation = !delta ? 0 : delta / (light <= 0.5 ? max + min : 2 - max - min)
    let hue = !delta ? 0 : max === r ? (g - b) / delta : max === g ? 2 + (b - r) / delta : 4 + (r - g) / delta
    hue = (hue / 6 + 1) % 1
    lines.push(`\t--${name}: ${(hue * 360).toFixed(4)} ${(saturation * 100).toFixed(4)}% ${(light * 100).toFixed(4)}%;`)
  }
  for (const group of ['space', 'radius', 'motion'] as const) {
    for (const [name, value] of Object.entries(tokens[group]))
      lines.push(`\t--${group}-${name}: ${value}${group === 'motion' ? 'ms' : 'px'};`)
  }
  lines.push('\t--radius: var(--radius-base);', '\t--font-display: \'Poppins\', ui-sans-serif, system-ui, sans-serif;', '\t--font-sans: \'Inter\', ui-sans-serif, system-ui, sans-serif;', '\t--font-mono: ui-monospace, monospace;', '}', '')
  return lines.join('\n')
}
export function brandTokens(check = false): void {
  const expected = tokenCss(JSON.parse(readFileSync(resolve(design, 'tokens.json'), 'utf8')) as Tokens)
  const file = resolve(root, 'apps/webapp/src/lib/design-system/tokens.css')
  if (check) {
    if (readFileSync(file, 'utf8') !== expected)
      throw new Error('Brand token drift; run generate brand')
  }
  else {
    writeFileSync(file, expected)
  }
}
export function contrast(a: string, b: string): number {
  const luminance = (hex: string) => [1, 3, 5].map(i => Number.parseInt(hex.slice(i, i + 2), 16) / 255).map(v => v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4).reduce((sum, v, i) => sum + v * [0.2126, 0.7152, 0.0722][i]!, 0)
  const x = luminance(a)
  const y = luminance(b)
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)
}
const literal = /Colors\.[A-Za-z]+(?:\.shade\d+)?|#[0-9a-fA-F]{3,8}\b|0x[0-9a-fA-F]{8}\b|(?:bg|text|border|ring|fill|stroke)-(?:red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|slate|gray|zinc|neutral|stone)-\d{2,3}\b|(?:rgba?|hsla?)\(\s*\d|(?:text|rounded(?:-[a-z]+)?|shadow|duration|gap|[mp][xytrbl]?)-\[[^\]]+\]|(?:fontSize|letterSpacing|elevation):\s*-?\d+(?:\.\d+)?|BorderRadius\.circular\(\s*\d+(?:\.\d+)?/g
export function brandCheck(recordReviewedBaseline = false): void {
  brandTokens(true)
  const tokens = JSON.parse(readFileSync(resolve(design, 'tokens.json'), 'utf8')) as Tokens
  const allowed = JSON.parse(readFileSync(resolve(design, 'visual-literals.json'), 'utf8')) as Record<string, number>
  const inventory = JSON.parse(readFileSync(resolve(design, 'assets.json'), 'utf8')) as Record<string, string>
  const assets = ['apps/webapp/static/brand', 'apps/webapp/static/fonts'].flatMap(path => files(resolve(root, path)))
  assets.push(resolve(root, 'apps/webapp/src/lib/assets/favicon.svg'))
  const actual = Object.fromEntries(assets.filter(path => !path.split('/').at(-1)!.startsWith('.')).map(path => [relative(root, path), digest(readFileSync(path))]))
  if (!recordReviewedBaseline && (Object.keys(actual).length !== Object.keys(inventory).length || Object.entries(actual).some(([name, hash]) => inventory[name] !== hash)))
    throw new Error('Brand assets changed')
  for (const name of ['Inter-Variable.woff2', 'Poppins-SemiBold.woff2', 'Inter-OFL.txt', 'Poppins-OFL.txt']) {
    if (!Object.keys(actual).some(path => path.endsWith(`/${name}`)))
      throw new Error(`Missing bundled font/license ${name}`)
  }
  const literals: Record<string, number> = {}
  for (const file of files(resolve(root, 'apps/webapp/src')).filter(file => /\.(?:ts|css|svelte)$/.test(file) && !file.endsWith('/tokens.css') && !file.includes('/l10n/'))) {
    const text = readFileSync(file, 'utf8')
    if (/fonts\.googleapis|GoogleFonts\.|package:google_fonts|Fraunces|Nunito|GalakRound|JetBrains/.test(text))
      throw new Error(`Invalid typography: ${relative(root, file)}`)
    const counts: Record<string, number> = {}
    for (const match of text.matchAll(literal)) {
      const key = `${relative(root, file)}::${match[0]}`
      counts[key] = (counts[key] ?? 0) + 1
    }
    Object.assign(literals, counts)
    if (!recordReviewedBaseline && Object.entries(counts).some(([key, count]) => count > (allowed[key] ?? 0)))
      throw new Error(`Unreviewed visual literals: ${relative(root, file)}`)
  }
  for (const colors of Object.values(tokens.colors)) {
    for (const [a, b] of [['foreground', 'background'], ['foreground', 'card'], ['muted-foreground', 'card'], ['muted-foreground', 'background'], ['primary-foreground', 'primary'], ['highlight', 'highlight-soft'], ['success', 'success-soft'], ['destructive', 'destructive-soft'], ['sky', 'sky-soft']]) {
      if (contrast(colors[a!]!, colors[b!]!) < 4.5)
        throw new Error('Text contrast fails 4.5:1')
    }
    if (contrast(colors.input!, colors.card!) < 3)
      throw new Error('Control contrast fails 3:1')
  }
  if (recordReviewedBaseline) {
    writeJson(resolve(design, 'assets.json'), actual)
    writeJson(resolve(design, 'visual-literals.json'), literals)
  }
}
export async function brandGallery(repository = root): Promise<void> {
  const directory = resolve(repository, 'apps/webapp/.screenshots/design-review')
  const screenshots = files(resolve(directory, 'current')).filter(file => file.endsWith('.png'))
  if (!screenshots.length)
    throw new Error('No review screenshots; place PNG captures in apps/webapp/.screenshots/design-review/current before running generate gallery')
  const manifest = resolve(directory, 'manifest.json')
  const previous = existsSync(manifest)
    ? JSON.parse(readFileSync(manifest, 'utf8')) as {
      captures: Record<string, unknown>[]
    }
    : { captures: [] }
  const sourceInputs = ['apps/webapp/src', 'apps/webapp/static', 'design-system/tokens.json']
  const hash = createHash('sha256')
  for (const source of sourceInputs) {
    for (const file of statSync(resolve(repository, source)).isFile() ? [resolve(repository, source)] : files(resolve(repository, source)))
      hash.update(`${relative(repository, file)}\0`).update(readFileSync(file))
  }
  const sourceDigest = hash.digest('hex')
  const revision = await run(['git', 'rev-parse', 'HEAD'], { cwd: repository, quiet: true })
  const version = (JSON.parse(readFileSync(resolve(repository, 'design-system/tokens.json'), 'utf8')) as Tokens).version
  const captures = screenshots.map((file) => {
    const data = readFileSync(file)
    const name = file.split('/').at(-1)!
    const path = relative(directory, file)
    if (data.length < 24 || !data.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])))
      throw new Error('Invalid PNG')
    const checksum = digest(data)
    const old = previous.captures.find(entry => entry.file === path && entry.sha256 === checksum)
    const desktop = name.includes('desktop')
    const component = name.startsWith('components-')
    const viewport = { width: desktop ? (/^students?-/.test(name) ? 1440 : 1280) : name.includes('tablet') ? 1024 : 390, height: desktop ? (component || /^students?-/.test(name) ? 1000 : 800) : name.includes('tablet') ? 1366 : 844 }
    return { viewport, locale: name.includes('-en') ? 'en' : 'fr', theme: name.includes('-dark') ? 'dark' : 'light', textScale: name.includes('-large') ? 2 : 1, keyboardInset: name.includes('-keyboard') ? 320 : 0, captureKind: component ? 'production-component-composition' : 'production-page', fixtureSource: component ? 'dev-only /__design; fictional values, no API writes' : 'isolated local Identity/School API with disposable seeded data', ...old, file: path, app: 'webapp', sha256: checksum, sourceRevision: old?.sourceRevision ?? revision, sourceDigest: old?.sourceDigest ?? sourceDigest, sourceState: old?.sourceState ?? 'working-tree', designSystemVersion: old?.designSystemVersion ?? version, capturedAt: old?.capturedAt ?? statSync(file).mtime.toISOString(), imagePixels: { width: data.readUInt32BE(16), height: data.readUInt32BE(20) } }
  })
  writeJson(manifest, { app: 'webapp', designSystemVersion: version, sourceDigestInputs: sourceInputs, captures })
  const escape = (s: string) => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;')
  writeFileSync(resolve(directory, 'index.html'), `<!doctype html><meta charset="utf-8"><title>EDAYA current UI</title><h1>Current UI</h1><a href="manifest.json">Capture provenance</a>${captures.map(c => `<figure><img style="max-width:100%" src="${escape(c.file)}" alt="${escape(c.file)}"><figcaption>${escape(c.file)}</figcaption></figure>`).join('')}`)
}
