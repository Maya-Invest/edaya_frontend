export const CLIENT_BINDINGS_OPENAPI_EXTENSION = 'x-edaya-client-bindings'

export interface ClientEntityBinding {
  publicName: string
  schemaName: string
  allowDirectSave: boolean
}

export interface ClientCommandBinding {
  publicName: string
  requestSchemaName: string
  responseSchemaName: string
}

export interface ClientQueryBinding {
  publicName: string
  requestSchemaName: string
  responseSchemaName: string
}

export interface ClientBindingsDocument {
  entities: Record<string, ClientEntityBinding>
  commands: Record<string, ClientCommandBinding>
  queries: Record<string, ClientQueryBinding>
}

export function extractClientBindingsFromOpenApi(
  openApi: { info?: Record<string, unknown> },
): ClientBindingsDocument {
  const bindings = openApi.info?.[CLIENT_BINDINGS_OPENAPI_EXTENSION]
  if (!bindings || typeof bindings !== 'object') {
    throw new Error(
      `OpenAPI spec is missing info.${CLIENT_BINDINGS_OPENAPI_EXTENSION}`,
    )
  }

  return bindings as ClientBindingsDocument
}

export function formatClientBindingsTypeScript(
  clientBindings: ClientBindingsDocument,
): string {
  const formatted = JSON.stringify(clientBindings, null, 2)
    .split('\n')
    .map((line, index) => (index === 0 ? line : `  ${line}`))
    .join('\n')

  return `// This file is auto-generated by tooling/repo/openapi/generate-bindings.ts
// Do not edit manually.

export const clientBindings = ${formatted} as const

export type ClientBindings = typeof clientBindings
`
}
